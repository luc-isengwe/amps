"""Build the field-level banking manifest WITHOUT human confirmation and its
synthesized policy (configuration B_field), for the AgentDojo run.

Starting point: examples/banking_fields.yaml (field-level labels, human
confirmation allowed). The function security_first() of the banking study
removes human confirmation and the untrusted label from the call
requirements, exactly as for configuration B_field of the static study.

Outputs (from the project folder):
    examples/banking_fields_noH.yaml   manifest used by the runtime engine
    results/banking_policy_Bfield.json policy synthesized for that manifest

Usage:
    python experiments/make_banking_field_policy.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "experiments"))

from amps.graph import compile_manifest  # noqa: E402
from amps.manifest import load_manifest  # noqa: E402
from amps.policy import Policy  # noqa: E402
from amps.runtime import PolicyEngine, project_output  # noqa: E402
from amps.synthesis import synthesize_ilp  # noqa: E402
from amps.verify import verify  # noqa: E402
from banking_fields_study import load, security_first  # noqa: E402

TX = "get_most_recent_transactions"


def main() -> None:
    # 1. Field-level manifest without human confirmation, written to disk so
    #    that the runtime engine loads exactly the manifest the policy is for.
    d = security_first(load("banking_fields.yaml"))
    d["system"] = "agentdojo-banking-fields-noH"
    out_yaml = ROOT / "examples" / "banking_fields_noH.yaml"
    out_yaml.write_text(
        "# Generated by experiments/make_banking_field_policy.py from\n"
        "# examples/banking_fields.yaml (security_first: no human confirmation).\n"
        + yaml.safe_dump(d, sort_keys=False, allow_unicode=True),
        encoding="utf-8")
    m = load_manifest(out_yaml)

    # 2. Synthesis and verification.
    cg = compile_manifest(m)
    res = synthesize_ilp(cg)
    safe = verify(cg, res.policy).safe
    out_pol = ROOT / "results" / "banking_policy_Bfield.json"
    out_pol.parent.mkdir(exist_ok=True)
    res.policy.save(out_pol)
    print(f"manifest : {out_yaml.relative_to(ROOT)}")
    print(f"policy   : {out_pol.relative_to(ROOT)}  status={res.status} cost={res.cost:.1f} safe={safe}")
    print(f"gates    : {dict((e, md.value) for e, md in res.policy.gates.items())}")
    print(f"trusted fields of {TX}: {m.projected_fields(TX)}")

    # 3. Self-check of the runtime behaviour expected in AgentDojo
    #    (prefer_projection=True: the transaction list is always projected).
    pol = Policy.load(out_pol)
    e = PolicyEngine(manifest=m, policy=pol, prefer_projection=True)
    d1 = e.before_tool_call("assistant", TX)
    e.after_tool_result("assistant", TX)
    d2 = e.before_tool_call("assistant", "send_money")
    e2 = PolicyEngine(manifest=m, policy=pol, prefer_projection=True)
    e2.before_tool_call("assistant", "read_file")
    e2.after_tool_result("assistant", "read_file")
    d3 = e2.before_tool_call("assistant", "send_money")
    sample = [{"id": 1, "sender": "A", "recipient": "B", "amount": 10.0,
               "subject": "free text", "date": "2022-01-01", "recurring": False}]
    print("check: transactions delivered as view   :", d1.details.get("view"))
    print("check: send_money after projected list  :", "allowed" if d2.allowed else "BLOCKED")
    print("check: send_money after read_file       :", "allowed" if d3.allowed else "BLOCKED")
    print("check: projected record                 :", project_output(m, TX, sample))
    ok = d1.details.get("view") == "trusted" and d2.allowed and not d3.allowed \
        and "subject" not in project_output(m, TX, sample)[0] and safe
    print("ALL CHECKS PASSED" if ok else "CHECK FAILED")


if __name__ == "__main__":
    main()
