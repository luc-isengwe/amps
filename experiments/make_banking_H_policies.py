"""Build the banking manifests WITH human confirmation and their synthesized
policies (configurations B+H and B_field+H), for the AgentDojo runs.

The manifests are the ones of the static study (banking_fields_study.py):
  - B+H       : session-level labels, human confirmation allowed;
  - B_field+H : field-level labels, human confirmation allowed.

Outputs (from the project folder):
    examples/banking_session_H.yaml     results/banking_policy_BH.json
    examples/banking_fields_H.yaml      results/banking_policy_BfieldH.json

Usage:
    python experiments/make_banking_H_policies.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "experiments"))

from amps.graph import compile_manifest  # noqa: E402
from amps.manifest import load_manifest  # noqa: E402
from amps.policy import Policy  # noqa: E402
from amps.runtime import PolicyEngine  # noqa: E402
from amps.synthesis import synthesize_ilp  # noqa: E402
from amps.verify import verify  # noqa: E402
from banking_fields_study import honest_labels, load, session_level, with_human  # noqa: E402

CONFIGS = {
    "BH": ("banking_session_H.yaml", "agentdojo-banking-session-H",
           lambda f: with_human(session_level(f))),
    "BfieldH": ("banking_fields_H.yaml", "agentdojo-banking-fields-H",
                lambda f: with_human(honest_labels(f))),
}


def build(name: str, yaml_name: str, system: str, make) -> None:
    d = make(load("banking_fields.yaml"))
    d["system"] = system
    out_yaml = ROOT / "examples" / yaml_name
    out_yaml.write_text(
        "# Generated by experiments/make_banking_H_policies.py "
        f"(configuration {name}: human confirmation allowed).\n"
        + yaml.safe_dump(d, sort_keys=False, allow_unicode=True),
        encoding="utf-8")
    m = load_manifest(out_yaml)
    cg = compile_manifest(m)
    res = synthesize_ilp(cg)
    safe = verify(cg, res.policy).safe
    out_pol = ROOT / "results" / f"banking_policy_{name}.json"
    out_pol.parent.mkdir(exist_ok=True)
    res.policy.save(out_pol)
    print(f"[{name}] manifest: {out_yaml.relative_to(ROOT)}")
    print(f"[{name}] policy  : {out_pol.relative_to(ROOT)} status={res.status} "
          f"cost={res.cost:.1f} secure={safe}")
    print(f"[{name}] gates   : {dict((e, md.value) for e, md in res.policy.gates.items())}")

    # Self-check: after reading a file, send_money must ask for a confirmation,
    # and the decision must follow the answer of the confirmation function.
    pol = Policy.load(out_pol)
    for answer in (True, False):
        asked = []
        e = PolicyEngine(manifest=m, policy=pol,
                         confirm=lambda agent, tool, label: asked.append(tool) or answer)
        e.before_tool_call("assistant", "read_file")
        e.after_tool_result("assistant", "read_file")
        dec = e.before_tool_call("assistant", "send_money")
        print(f"[{name}] check: confirm={answer!s:5} -> send_money "
              f"{'allowed' if dec.allowed else 'refused'} ({dec.reason}); asked={asked}")


def main() -> None:
    for name, (yaml_name, system, make) in CONFIGS.items():
        build(name, yaml_name, system, make)


if __name__ == "__main__":
    main()
