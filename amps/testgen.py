"""Generate pytest regression tests from witnesses.

For every new attack path found by the impact analysis we write one test
case. Each test loads the manifest and the policy, replays the attack path
against the runtime engine and asserts that the violating flow never
reaches the sink. Running ``pytest`` in the deployment pipeline then
guarantees that a later change cannot silently re-open the path.

Two files are written in ``out_dir``:

* ``<name>.json``     the scenarios (witnesses as data, easy to inspect)
* ``test_<name>.py``  a small, generic test module that reads the JSON

Keeping the scenarios as data (instead of generating one Python function per
witness) keeps the generated code short and reviewable.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Iterable

from .verify import Witness

_TEMPLATE = '''"""AUTO-GENERATED regression tests ({name}).

Generated by `amps impact`. Do not edit by hand: re-run the impact analysis.
Each scenario is an attack path that the change introduced. The test passes
if the runtime engine, configured with the policy, stops the attack.
"""

import json
from pathlib import Path

import pytest

from amps.manifest import load_manifest
from amps.policy import Policy
from amps.replay import replay_witness
from amps.runtime import PolicyEngine
from amps.verify import Witness

HERE = Path(__file__).parent
DATA = json.loads((HERE / "{name}.json").read_text(encoding="utf-8"))
MANIFEST = (HERE / DATA["manifest"]).resolve()
POLICY = (HERE / DATA["policy"]).resolve()


@pytest.mark.parametrize("scenario", DATA["scenarios"], ids=[s["id"] for s in DATA["scenarios"]])
def test_attack_path_is_blocked(scenario):
    engine = PolicyEngine(load_manifest(MANIFEST), Policy.load(POLICY))
    result = replay_witness(engine, Witness.from_dict(scenario["witness"]))
    assert not result.violation, (
        f"attack path {{scenario['id']}} reached the sink: "
        f"{{[d.action for d in result.decisions]}}")
'''


def generate_regression_tests(witnesses: Iterable[Witness], manifest_path: str | Path,
                              policy_path: str | Path, out_dir: str | Path,
                              name: str = "generated") -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    scenarios = []
    for i, w in enumerate(witnesses, 1):
        scenarios.append({
            "id": f"{name}-{i:03d}-{w.property}-{w.sink_tool}",
            "witness": w.to_dict(),
        })
    data = {
        # Paths are stored relative to the test file so the folder can move.
        "manifest": os.path.relpath(Path(manifest_path).resolve(), out_dir.resolve()),
        "policy": os.path.relpath(Path(policy_path).resolve(), out_dir.resolve()),
        "scenarios": scenarios,
    }
    json_path = out_dir / f"{name}.json"
    py_path = out_dir / f"test_{name}.py"
    json_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    py_path.write_text(_TEMPLATE.format(name=name), encoding="utf-8")
    return json_path, py_path
